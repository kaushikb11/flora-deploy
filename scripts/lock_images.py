"""Regenerate the Modal image locks in ``src/flora_deploy/modal_app/locks/``.

For each image, writes ``<image>.in`` from the ``*_PACKAGES`` tuples in ``modal_app/images.py``
(which take their versions from ``config.pins.RUNTIME``) and compiles it into ``<image>.txt``:
every transitive dependency with an exact version and sha256 hashes, for linux x86_64 at the base
image's glibc (``images.LOCK_PLATFORMS``) / CPython 3.12, wheels only. The compile runs the same
uv version the images install with (``RUNTIME["uv"]``, fetched through ``uvx``). All wheels,
including torch 2.11.0 (cu130) and its ``nvidia-*`` CUDA wheels, come from PyPI, exactly as
NVIDIA's ``pip install -r requirements.txt`` and vLLM's own torch pin get them.

Usage: uv run python scripts/lock_images.py [--upgrade] [cpu hfref vllm]
  --upgrade re-resolves from scratch; by default versions already in a lock are kept where the
  inputs still allow them (uv's usual ``pip compile`` preference for the output file).

Changing a lock changes ``images.image_fingerprint()`` and therefore the config hash (PLAN.md D11).
"""

from __future__ import annotations

import argparse
import subprocess
import sys

from flora_deploy.config.pins import RUNTIME
from flora_deploy.modal_app.images import LOCK_DIR, LOCK_FILES, LOCK_PLATFORMS, PACKAGES

SHORT = {"cpu": "img_cpu", "hfref": "img_hfref", "vllm": "img_vllm"}
COMMAND = "uv run python scripts/lock_images.py"


def write_input(name: str) -> str:
    path = LOCK_DIR / LOCK_FILES[name].replace(".txt", ".in")
    body = "".join(f"{req}\n" for req in PACKAGES[name])
    path.write_text(f"# Generated by {COMMAND} from modal_app/images.py; do not edit.\n{body}")
    return str(path)


def compile_lock(name: str, upgrade: bool) -> None:
    src = write_input(name)
    out = LOCK_DIR / LOCK_FILES[name]
    cmd = [
        "uvx", f"uv@{RUNTIME['uv']}", "pip", "compile", src,
        "--output-file", str(out),
        "--python-platform", LOCK_PLATFORMS[name],
        "--python-version", RUNTIME["python_image"],
        "--generate-hashes",
        "--no-build",
        "--index-url", "https://pypi.org/simple",
        "--custom-compile-command", COMMAND,
        "--quiet",
    ]
    if upgrade:
        cmd.append("--upgrade")
    print(f"locking {name} -> {out.name}", flush=True)
    subprocess.run(cmd, check=True)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("images", nargs="*", help=f"subset of {', '.join(SHORT)} (default: all)")
    ap.add_argument("--upgrade", action="store_true")
    args = ap.parse_args()
    if bad := sorted(set(args.images) - set(SHORT)):
        ap.error(f"unknown image(s): {bad}")
    LOCK_DIR.mkdir(exist_ok=True)
    for short in args.images or SHORT:
        compile_lock(SHORT[short], args.upgrade)
    return 0


if __name__ == "__main__":
    sys.exit(main())
