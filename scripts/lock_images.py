"""Regenerate the Modal image locks in ``src/flora_deploy/modal_app/locks/``.

For each image, writes ``<image>.in`` from the ``*_PACKAGES`` tuples in ``modal_app/images.py``
(which take their versions from ``config.pins.RUNTIME``) and compiles it into ``<image>.txt``:
every transitive dependency with an exact version and sha256 hashes, for linux x86_64 at the base
image's glibc and CPython (``images.LOCK_PLATFORMS`` / ``LOCK_PYTHON``), wheels only. The compile
runs the same uv version the images install with (``RUNTIME["uv"]``, fetched through ``uvx``).
Wheels come from PyPI, except img_hfref's torch and torchvision: ``images.OVERRIDES`` (written to
``<image>.overrides.txt`` and passed as ``--overrides``) replaces them with the exact +cu128 wheels
from https://download.pytorch.org/whl/cu128 by URL and sha256 (NVIDIA's TempSeg/Captioner install
recipe). Their ``nvidia-*-cu12`` / triton deps resolve from PyPI.

The output does not depend on the caller: the compile runs from the repo root with repo-relative
paths (so ``# via`` annotations are stable), ignores uv config files (``--no-config``) and drops
``UV_*`` / ``PIP_*`` variables from the environment.

Usage: uv run python scripts/lock_images.py [--upgrade] [cpu hfref vllm]
  --upgrade re-resolves from scratch; by default versions already in a lock are kept where the
  inputs still allow them (uv's usual ``pip compile`` preference for the output file).

Changing a lock's requirements changes ``images.image_fingerprint()`` and therefore the config
hash (PLAN.md D11); comments do not.
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

from flora_deploy.config.pins import RUNTIME
from flora_deploy.modal_app.images import (
    LOCK_DIR,
    LOCK_FILES,
    LOCK_PLATFORMS,
    LOCK_PYTHON,
    OVERRIDES,
    PACKAGES,
)

SHORT = {"cpu": "img_cpu", "hfref": "img_hfref", "vllm": "img_vllm"}
COMMAND = "uv run python scripts/lock_images.py"
REPO_ROOT = Path(__file__).resolve().parents[1]


def _write(path: Path, reqs: tuple[str, ...]) -> Path:
    body = "".join(f"{req}\n" for req in reqs)
    path.write_text(f"# Generated by {COMMAND} from modal_app/images.py; do not edit.\n{body}")
    return path


def write_input(name: str) -> Path:
    return _write(LOCK_DIR / LOCK_FILES[name].replace(".txt", ".in"), PACKAGES[name])


def write_overrides(name: str) -> list[str]:
    path = LOCK_DIR / LOCK_FILES[name].replace(".txt", ".overrides.txt")
    if not OVERRIDES[name]:
        path.unlink(missing_ok=True)
        return []
    _write(path, OVERRIDES[name])
    return ["--overrides", str(path.resolve().relative_to(REPO_ROOT))]


def _env() -> dict[str, str]:
    return {k: v for k, v in os.environ.items() if not k.startswith(("UV_", "PIP_"))}


def compile_lock(name: str, upgrade: bool) -> None:
    src = write_input(name).resolve().relative_to(REPO_ROOT)
    out = (LOCK_DIR / LOCK_FILES[name]).resolve().relative_to(REPO_ROOT)
    cmd = [
        "uvx", f"uv@{RUNTIME['uv']}", "pip", "compile", str(src),
        "--no-config",
        "--output-file", str(out),
        "--python-platform", LOCK_PLATFORMS[name],
        "--python-version", LOCK_PYTHON[name],
        "--generate-hashes",
        "--no-build",
        "--index-url", "https://pypi.org/simple",
        *write_overrides(name),
        "--custom-compile-command", COMMAND,
        "--quiet",
    ]
    if upgrade:
        cmd.append("--upgrade")
    print(f"locking {name} -> {out.name}", flush=True)
    subprocess.run(cmd, check=True, cwd=REPO_ROOT, env=_env())


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("images", nargs="*", help=f"subset of {', '.join(SHORT)} (default: all)")
    ap.add_argument("--upgrade", action="store_true")
    args = ap.parse_args()
    if bad := sorted(set(args.images) - set(SHORT)):
        ap.error(f"unknown image(s): {bad}")
    LOCK_DIR.mkdir(exist_ok=True)
    for short in args.images or SHORT:
        compile_lock(SHORT[short], args.upgrade)
    return 0


if __name__ == "__main__":
    sys.exit(main())
