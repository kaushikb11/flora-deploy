"""Regenerate the Modal image locks in ``src/flora_deploy/modal_app/locks/``.

For each image, writes ``<image>.in`` from the ``*_PACKAGES`` tuples in ``modal_app/images.py``
(which take their versions from ``config.pins.RUNTIME``) and compiles it into ``<image>.txt``:
every transitive dependency with an exact version and sha256 hashes, for linux x86_64 at the base
image's glibc and CPython (``images.LOCK_PLATFORMS`` / ``LOCK_PYTHON``), wheels only. The compile
runs the same uv version the images install with (``RUNTIME["uv"]``, fetched through ``uvx``).
Wheels come from PyPI, except img_hfref's torch and torchvision: ``images.OVERRIDES`` (written to
``<image>.overrides.txt`` and passed as ``--overrides``) replaces them with the exact +cu128 wheels
from https://download.pytorch.org/whl/cu128 by URL and sha256 (NVIDIA's TempSeg/Captioner install
recipe). Their ``nvidia-*-cu12`` / triton deps resolve from PyPI.

The output does not depend on the caller: the compile runs from the repo root with repo-relative
paths (so ``# via`` annotations are stable), ignores uv config files (``--no-config``) and drops
``UV_*`` / ``PIP_*`` variables from the environment.

Usage: uv run python scripts/lock_images.py [--upgrade | --check] [cpu hfref vllm]
  --upgrade re-resolves from scratch; by default versions already in a lock are kept where the
  inputs still allow them (uv's usual ``pip compile`` preference for the output file).
  --check writes nothing under the repo: it re-resolves each lock exactly as the default mode
  would, in a scratch copy of the lock directory (same repo-relative paths, seeded with the
  committed lock), and exits 1 naming every ``.in`` / ``.overrides.txt`` / ``.txt`` a re-lock
  would change (2 if a compile fails). It needs the network (PyPI, the PyTorch index), never
  Modal.

Changing a lock's requirements changes ``images.image_fingerprint()`` and therefore the config
hash (PLAN.md D11); comments do not.
"""

from __future__ import annotations

import argparse
import difflib
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from flora_deploy.config.pins import RUNTIME
from flora_deploy.modal_app.images import (
    LOCK_DIR,
    LOCK_FILES,
    LOCK_PLATFORMS,
    LOCK_PYTHON,
    OVERRIDES,
    PACKAGES,
)

SHORT = {"cpu": "img_cpu", "hfref": "img_hfref", "vllm": "img_vllm"}
COMMAND = "uv run python scripts/lock_images.py"
REPO_ROOT = Path(__file__).resolve().parents[1]
DIFF_LINES = 20  # diff lines shown per stale lock file in --check output


def _text(reqs: tuple[str, ...]) -> str:
    body = "".join(f"{req}\n" for req in reqs)
    return f"# Generated by {COMMAND} from modal_app/images.py; do not edit.\n{body}"


def input_text(name: str) -> str:
    """What ``<image>.in`` must contain."""
    return _text(PACKAGES[name])


def overrides_text(name: str) -> str | None:
    """What ``<image>.overrides.txt`` must contain, or None when it must not exist."""
    return _text(OVERRIDES[name]) if OVERRIDES[name] else None


def _files(name: str) -> tuple[str, str, str]:
    """(input, overrides, lock) file names inside the lock directory."""
    lock = LOCK_FILES[name]
    return lock.replace(".txt", ".in"), lock.replace(".txt", ".overrides.txt"), lock


def _lock_rel() -> Path:
    return LOCK_DIR.resolve().relative_to(REPO_ROOT)


def _write_inputs(name: str, lock_dir: Path) -> None:
    src, ovr, _ = _files(name)
    (lock_dir / src).write_text(input_text(name))
    if (text := overrides_text(name)) is None:
        (lock_dir / ovr).unlink(missing_ok=True)
    else:
        (lock_dir / ovr).write_text(text)


def compile_cmd(name: str, upgrade: bool) -> list[str]:
    """The ``uv pip compile`` command for ``name``. Paths are repo-relative, so it runs from any
    root whose copy of the lock directory holds the inputs, with identical output."""
    src, ovr, out = (str(_lock_rel() / f) for f in _files(name))
    cmd = [
        "uvx", f"uv@{RUNTIME['uv']}", "pip", "compile", src,
        "--no-config",
        "--output-file", out,
        "--python-platform", LOCK_PLATFORMS[name],
        "--python-version", LOCK_PYTHON[name],
        "--generate-hashes",
        "--no-build",
        "--index-url", "https://pypi.org/simple",
        *(["--overrides", ovr] if OVERRIDES[name] else []),
        "--custom-compile-command", COMMAND,
        "--quiet",
    ]
    if upgrade:
        cmd.append("--upgrade")
    return cmd


def _env() -> dict[str, str]:
    return {k: v for k, v in os.environ.items() if not k.startswith(("UV_", "PIP_"))}


def _run(cmd: list[str], cwd: Path) -> None:
    """Run a compile: the only network step (tests patch it)."""
    subprocess.run(cmd, check=True, cwd=cwd, env=_env())


def compile_lock(name: str, upgrade: bool) -> None:
    _write_inputs(name, LOCK_DIR)
    print(f"locking {name} -> {LOCK_FILES[name]}", flush=True)
    _run(compile_cmd(name, upgrade), REPO_ROOT)


def _read(path: Path) -> str | None:
    return path.read_text() if path.exists() else None


def _diff(rel: Path, old: str | None, new: str | None) -> list[str]:
    if old == new:
        return []
    if new is None:
        return [f"{rel}: would be removed"]
    if old is None:
        return [f"{rel}: missing"]
    lines = [ln.rstrip("\n") for ln in difflib.unified_diff(
        old.splitlines(keepends=True), new.splitlines(keepends=True),
        f"a/{rel}", f"b/{rel}", n=0)]
    more = [f"... {len(lines) - DIFF_LINES} more"] if len(lines) > DIFF_LINES else []
    return [f"{rel}: would change", *lines[:DIFF_LINES], *more]


def check_lock(name: str) -> list[str]:
    """Re-resolve ``name`` as the default mode would, in a scratch copy of the lock directory,
    and return what a re-lock would change (empty when the committed files are current)."""
    src, ovr, out = _files(name)
    rel = _lock_rel()
    with tempfile.TemporaryDirectory(prefix="lock-check-") as tmp:
        root = Path(tmp)
        lock_dir = root / rel
        lock_dir.mkdir(parents=True)
        if (REPO_ROOT / ".python-version").exists():  # uv reads it from the cwd
            shutil.copy2(REPO_ROOT / ".python-version", root / ".python-version")
        if (LOCK_DIR / out).exists():  # the default mode prefers the committed versions
            shutil.copy2(LOCK_DIR / out, lock_dir / out)
        _write_inputs(name, lock_dir)
        _run(compile_cmd(name, upgrade=False), root)
        problems: list[str] = []
        for f in (src, ovr, out):
            problems += _diff(rel / f, _read(LOCK_DIR / f), _read(lock_dir / f))
        return problems


def check(shorts: list[str]) -> int:
    stale = []
    for short in shorts:
        name = SHORT[short]
        print(f"checking {name} -> {LOCK_FILES[name]}", flush=True)
        try:
            problems = check_lock(name)
        except (subprocess.CalledProcessError, OSError) as e:
            print(f"{name}: compile failed: {e}", file=sys.stderr, flush=True)
            return 2
        if problems:
            stale.append(name)
            print("\n".join(problems), flush=True)
    if stale:
        print(f"stale lock(s): {', '.join(stale)}; run {COMMAND}, then commit the locks",
              file=sys.stderr, flush=True)
        return 1
    print(f"locks current: {', '.join(SHORT[s] for s in shorts)}", flush=True)
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("images", nargs="*", help=f"subset of {', '.join(SHORT)} (default: all)")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--upgrade", action="store_true", help="re-resolve from scratch")
    mode.add_argument("--check", action="store_true",
                      help="write nothing; exit 1 if a re-lock would change the committed locks")
    args = ap.parse_args(argv)
    if bad := sorted(set(args.images) - set(SHORT)):
        ap.error(f"unknown image(s): {bad}")
    shorts = args.images or list(SHORT)
    if args.check:
        return check(shorts)
    LOCK_DIR.mkdir(exist_ok=True)
    for short in shorts:
        compile_lock(SHORT[short], args.upgrade)
    return 0


if __name__ == "__main__":
    sys.exit(main())
