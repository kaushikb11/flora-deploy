"""Generate ``docs/cli.md`` from the typer app, so the command reference cannot drift.

    uv run python scripts/cli_docs.py            # print it
    uv run python scripts/cli_docs.py --write    # rewrite docs/cli.md

``tests/unit/test_cli_docs.py`` fails when ``docs/cli.md`` differs from :func:`render` or misses a
registered command.
"""

from __future__ import annotations

import sys
from enum import Enum
from pathlib import Path

DOC = Path(__file__).resolve().parents[1] / "docs" / "cli.md"

# Workflow order; any command not listed is appended, so none is ever left out.
ORDER = ["init", "doctor", "prepare", "index", "plan", "estimate", "deploy", "run", "status",
         "logs", "cancel", "resume", "report", "results", "compose", "certify", "version"]

JOB_SCOPED = {"status", "logs", "cancel", "resume", "report", "results"}

HEADER = """\
# `flora` command reference

<!-- Generated by scripts/cli_docs.py from the typer app; do not edit by hand.
     Regenerate: uv run python scripts/cli_docs.py --write -->

Every command takes `--help`. Most read `flora.yaml` from the current directory (`--config` to
point elsewhere).

## Where the job and the store come from

The job commands (`flora status`, `logs`, `cancel`, `resume`, `report` and `results`) take the job
id as an optional argument (`--job` for `results`) and the store as an optional `--store`:

| | Default | Override |
|---|---|---|
| job id | the config's `project` | the `JOB` argument (`results`: `--job`) |
| store | `output.sink`, then `flora-local-store/` (1) | `--store URI`, `FLORA_STORE` |
| config | `./flora.yaml` | `--config PATH` |

(1) The config's `output.sink` (`volume://x` is the Modal Volume `x`), then the local store
that `flora run --local` writes, `flora-local-store/` next to `flora.yaml`, when it exists.

Fake-models runs (`--fake-models`, and every `--local` run) use the job id `<project>.fake`, so
they never mix with real jobs. With the job id left to its default, a command uses the real run;
when there is none but a fake-models run exists it uses that one and prints one line saying the
results come from stand-in models. When both exist it uses the real one and says the fake one
exists. A job id you pass by name is used exactly as given.

`flora index` writes its summary to `summary.json` next to `flora.yaml`, and `flora plan` reads
it from there when you give no `--index` or `--video-hours`.

## Exit codes

| Code | Meaning |
|---|---|
| 0 | done (or still running: `status`, `run --detach`) |
| 1 | failed |
| 2 | refused, or a usage error (bad config or arguments, job not found, internal error) |
| 3 | completed with some episodes excluded (`completed_with_errors`) |
| 4 | stopped by the budget (`budget_stopped`) |
| 5 | cancelled or stopped (local runs: also interrupted, or the job's lease is held) |

130 means interrupted with Ctrl-C.

## Commands
"""


def _app_command():
    import typer

    from flora_deploy.cli import app

    return typer.main.get_command(app)


def commands() -> dict:
    """Registered command name -> click command (hidden ones included)."""
    return dict(_app_command().commands)


def _cell(text: str) -> str:
    text = text.replace("\\[", "[").replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")
    return " ".join(text.split())


def _default(p) -> str:
    d = p.default
    if callable(d):
        return ""
    if getattr(p, "is_flag", False) and not getattr(p, "secondary_opts", None):
        return "off" if not d else "on"
    if d is None or d == () or d == []:
        return ""
    if isinstance(d, bool):
        return p.opts[0] if d else (p.secondary_opts or ["off"])[0]
    if isinstance(d, Enum):
        d = d.value
    return f"`{d}`"


def _purpose(cmd) -> str:
    text = (cmd.help or "").split("\n\n", 1)[0]
    return " ".join(text.split())


def _usage(name: str, cmd) -> str:
    args = []
    for p in cmd.params:
        if p.param_type_name == "argument" and not p.hidden:
            meta = p.name.upper()
            args.append(meta if p.required else f"[{meta}]")
    return " ".join(["flora", name, *args, "[OPTIONS]" if any(
        p.param_type_name == "option" and not p.hidden for p in cmd.params) else ""]).strip()


def render() -> str:
    cmds = commands()
    names = [n for n in ORDER if n in cmds] + sorted(n for n in cmds if n not in ORDER)
    out = [HEADER]
    for name in names:
        cmd = cmds[name]
        if cmd.hidden:
            continue
        out.append(f"### `flora {name}`\n")
        out.append(f"{_purpose(cmd)}\n")
        out.append(f"```\n{_usage(name, cmd)}\n```\n")
        if name in JOB_SCOPED:
            out.append("Job and store default from `flora.yaml` "
                       "([above](#where-the-job-and-the-store-come-from)).\n")
        rows = []
        for p in cmd.params:
            if p.hidden or p.name == "help":
                continue
            if p.param_type_name == "argument":
                label = f"`{p.name.upper()}`"
            else:
                opts = [*p.opts, *getattr(p, "secondary_opts", [])]
                label = ", ".join(f"`{o}`" for o in opts)
                if getattr(p, "envvar", None):
                    label += f" (env `{p.envvar}`)"
            req = "required" if p.required else _default(p)
            rows.append(f"| {label} | {_cell(req)} | {_cell(getattr(p, 'help', None) or '')} |")
        if rows:
            out.append("| Argument / option | Default | |\n|---|---|---|\n" + "\n".join(rows)
                       + "\n")
    return "\n".join(out).rstrip() + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if argv[:1] == ["--write"]:
        DOC.write_text(text, encoding="utf-8")
        print(f"wrote {DOC}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
