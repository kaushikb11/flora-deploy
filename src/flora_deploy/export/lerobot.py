"""``flora export --to lerobot``: a copy of the source LeRobot dataset with Flora's labels in it.

The source dataset is never modified. The export is a new directory that holds a copy of the
source's ``meta/`` and ``data/`` with the labels added (``docs/export.md`` is the reference):

* episode metadata (``meta/episodes.jsonl`` in v2.1, ``meta/episodes/chunk-*/file-*.parquet`` in
  v3.0) gains ``flora_subtasks``, ``flora_terminal_score``, ``flora_terminal_expected``,
  ``flora_certified`` and ``flora_provenance`` (only the fields of the exported stages, plus the
  last two);
* every data parquet file gains the per-frame columns ``flora_dense_reward`` (``reward.dense``)
  and ``flora_subtask_index`` (``segment`` / ``caption``), declared in ``meta/info.json``
  ``features`` and in the file's ``huggingface`` schema metadata, as LeRobot does for its own
  features;
* ``meta/info.json`` gains a ``flora`` block (job, stages, source revision, the
  certification policy used, the alignment rule);
* ``flora_export_report.json`` (at the root) lists the episodes that got no label, and why.

Videos are not copied unless ``include_videos``: their paths are unchanged, so downloading the
source revision's ``videos/`` into the export directory completes it.

**Dense alignment.** NVIDIA's dense reward is one value per 0.5 s step of the episode
(``stages.reward.per_step``: ``ceil(duration / 0.5)`` steps, step ``k`` covering
``[0.5 k, 0.5 (k + 1))`` s from the episode start). A frame with LeRobot ``timestamp`` ``t``
(seconds from its episode's start) gets step ``k = floor((t + 1e-4) / 0.5)``; the 1e-4 s
absorbs float32 timestamp rounding at step boundaries. A frame with no such step (``k`` past
the last step, or a negative ``t``), and every frame of an episode without a dense record, gets
NaN: gaps are never filled from neighbouring steps. Values are NVIDIA's 1 (failure),
2 (suboptimal), 3 (normal), as float32.

**Subtask index.** A frame gets the index (into the episode's ``flora_subtasks``, ordered by
``start_s``) of the first subtask with ``start_s <= t + 1e-4 < end_s``, else -1.
"""

