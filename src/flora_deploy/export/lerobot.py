def _load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _rel(path: Path, root: Path) -> str:
    return path.relative_to(root).as_posix()


def _src(root: Path, rel: str) -> Path:
    """A source dataset file ``root / rel``, refused (ExportError) when it resolves outside the
    dataset (a symlink out of it; review 12 F1/F4). The dataset's metadata is untrusted."""
    try:
        return contain(root, rel)
    except UnsafePath as e:
        raise ExportError(f"{root}: {e}") from None


def _within(root: Path, f: Path) -> Path:
    """``f`` (found under ``root`` by a glob), refused when it resolves outside the dataset."""
    if not is_within(root, f):
        raise ExportError(f"{root}: {_rel(f, root)} resolves outside the dataset")
    return f


def _dst(tmp: Path, rel: str) -> Path:
    """The export file ``tmp / rel``; ``rel`` must stay inside the export directory."""
    try:
        return contain(tmp, rel)
    except UnsafePath as e:
        raise ExportError(f"refusing to write outside the export: {e}") from None


class _Layout:
    """What differs between v2.1 and v3.0: where episode rows and data files are."""

    version: str

    def __init__(self, root: Path, info: dict[str, Any]):
        self.root, self.info = root, info

    def episode_rows(self) -> list[dict[str, Any]]:
        raise NotImplementedError

    def episode_files(self) -> list[Path]:
        raise NotImplementedError

    def data_files(self) -> list[Path]:
        raise NotImplementedError

    def write_episodes(self, out_root: Path, labels: Mapping[int, EpisodeLabels | None],
                       fields: Sequence[str]) -> None:
        raise NotImplementedError


def _episode_values(lab: EpisodeLabels | None, fields: Sequence[str]) -> dict[str, Any]:
    vals = {
        "flora_subtasks": None if lab is None or lab.subtasks is None else list(lab.subtasks),
        "flora_terminal_score": None if lab is None else lab.terminal_score,
        "flora_terminal_expected": None if lab is None else lab.terminal_expected,
        "flora_certified": None if lab is None else lab.certified,
        "flora_provenance": None if lab is None else list(lab.provenance),
    }
    return {f: vals[f] for f in fields}


class _V21(_Layout):
    """v2.x: ``meta/episodes.jsonl``, one data parquet per episode (``data_path`` template)."""

    version = "v2.1"

    def episode_rows(self) -> list[dict[str, Any]]:
        path = self.root / "meta" / "episodes.jsonl"
        if not path.is_file():
            raise ExportError(f"{self.root}: missing meta/episodes.jsonl")
        path = _src(self.root, "meta/episodes.jsonl")
        return [json.loads(x) for x in path.read_text(encoding="utf-8").splitlines() if x.strip()]

    def episode_files(self) -> list[Path]:
        return [_src(self.root, "meta/episodes.jsonl")]

    def data_files(self) -> list[Path]:
        tpl = self.info.get("data_path")
        if not tpl:
            raise ExportError(f"{self.root}: meta/info.json has no data_path")
        size = int(self.info.get("chunks_size", 1000))
        out = []
        for row in self.episode_rows():
            e = int(row["episode_index"])
            try:
                rel = format_template(tpl, what="data_path", episode_chunk=e // size,
                                      episode_index=e)
            except UnsafePath as err:
                raise ExportError(f"{self.root}: {err}") from None
            p = self.root / rel
            if not p.is_file():
                raise ExportError(f"{self.root}: episode {e}: missing data file "
                                  f"{_rel(p, self.root)}")
            out.append(_src(self.root, rel))
        return out

    def write_episodes(self, out_root, labels, fields):
        lines = []
        for row in self.episode_rows():
            row.update(_episode_values(labels.get(int(row["episode_index"])), fields))
            lines.append(json.dumps(row, ensure_ascii=False, allow_nan=False))
        _dst(out_root, "meta/episodes.jsonl").write_text("\n".join(lines) + "\n",
                                                          encoding="utf-8")


class _V3(_Layout):
    """v3.x: ``meta/episodes/chunk-*/file-*.parquet`` and chunked data files."""

    version = "v3.0"

    def episode_files(self) -> list[Path]:
        d = self.root / "meta" / "episodes"
        files = sorted({*d.glob("chunk-*/file-*.parquet"), *d.glob("chunk-*/file_*.parquet")})
        if not files:
            raise ExportError(f"{self.root}: no meta/episodes/chunk-*/file-*.parquet")
        return [_within(self.root, f) for f in files]

    def episode_rows(self) -> list[dict[str, Any]]:
        rows: list[dict[str, Any]] = []
        for f in self.episode_files():
            names = pq.read_schema(f).names
            cols = [c for c in ("episode_index", "length", "data/chunk_index",
                                "data/file_index") if c in names]
            rows += pq.read_table(f, columns=cols).to_pylist()
        return rows

    def data_files(self) -> list[Path]:
        d = self.root / "data"
        files = sorted({*d.glob("chunk-*/file-*.parquet"), *d.glob("chunk-*/file_*.parquet")})
        if not files:
            raise ExportError(f"{self.root}: no data/chunk-*/file-*.parquet")
        return [_within(self.root, f) for f in files]

    def write_episodes(self, out_root, labels, fields):
        for f in self.episode_files():
            table = pq.read_table(f)
            idx = table.column("episode_index").to_pylist()
            for name in fields:
                if name in table.column_names:
                    raise ExportError(f"{_rel(f, self.root)} already has a {name} column "
                                      "(export from the original dataset)")
                vals = [_episode_values(labels.get(int(e)), fields)[name] for e in idx]
                table = table.append_column(pa.field(name, EPISODE_FIELDS[name][0]),
                                            pa.array(vals, type=EPISODE_FIELDS[name][0]))
            dst = _dst(out_root, _rel(f, self.root))
            dst.parent.mkdir(parents=True, exist_ok=True)
            pq.write_table(table, dst, compression=_compression(pq.ParquetFile(f)))


def open_layout(root: Path) -> _Layout:
    info_path = root / "meta" / "info.json"
    if not info_path.is_file():
        raise ExportError(f"{root}: not a LeRobot dataset (no meta/info.json)")
    info = _load_json(_src(root, "meta/info.json"))
    version = str(info.get("codebase_version", ""))
    if version.startswith("v3."):
        return _V3(root, info)
    if version.startswith("v2."):
        return _V21(root, info)
    raise ExportError(f"{root}: unsupported LeRobot codebase_version {version!r}")


def _compression(pf: pq.ParquetFile) -> str:
    md = pf.metadata
    if md.num_row_groups and md.num_columns:
        c = str(md.row_group(0).column(0).compression).lower()
        return "none" if c == "uncompressed" else c
    return "snappy"


def _hf_metadata(meta: Mapping[bytes, bytes] | None, add: Mapping[str, str]
                 ) -> dict[bytes, bytes] | None:
    """The parquet ``huggingface`` features metadata with ``add`` (column -> dtype) declared as
    ``Value`` features, the way ``datasets`` declares LeRobot's scalar features."""
    if not meta:
        return None
    out = dict(meta)
    raw = out.get(b"huggingface")
    if raw:
        doc = json.loads(raw)
        feats = doc.setdefault("info", {}).setdefault("features", {})
        for name, dtype in add.items():
            feats[name] = {"dtype": dtype, "_type": "Value"}
        out[b"huggingface"] = json.dumps(doc).encode()
    return out


@dataclass
class _FrameStats:
    frames: dict[int, int] = field(default_factory=dict)  # episode -> frames seen
    dense_nan: dict[int, int] = field(default_factory=dict)  # labeled episode -> NaN frames


def _rewrite_data(src: Path, dst: Path, labels: Mapping[int, EpisodeLabels | None],
                  columns: Sequence[str], stats: _FrameStats) -> None:
    pf = pq.ParquetFile(src)
    schema = pf.schema_arrow
    for c in ("episode_index", "timestamp"):
        if c not in schema.names:
            raise ExportError(f"{src}: data file has no {c!r} column")
    for c in columns:
        if c in schema.names:
            raise ExportError(f"{src} already has a {c!r} column (export from the original "
                              "dataset)")
    dtypes = {c: FRAME_FEATURES[c]["dtype"] for c in columns}
    new_schema = schema
    for c in columns:
        new_schema = new_schema.append(pa.field(c, pa.float32() if dtypes[c] == "float32"
                                                else pa.int64()))
    new_schema = new_schema.with_metadata(_hf_metadata(schema.metadata, dtypes))
    dst.parent.mkdir(parents=True, exist_ok=True)
    with pq.ParquetWriter(dst, new_schema, compression=_compression(pf)) as w:
        for i in range(pf.num_row_groups):
            t = pf.read_row_group(i)
            eps = np.asarray(t.column("episode_index").to_numpy(zero_copy_only=False),
                             dtype=np.int64)
            ts = np.asarray(t.column("timestamp").to_numpy(zero_copy_only=False),
                            dtype=np.float64)
            dense = np.full(len(t), np.nan, dtype=np.float32)
            sub = np.full(len(t), -1, dtype=np.int64)
            for e in np.unique(eps):
                m = eps == e
                lab = labels.get(int(e))
                stats.frames[int(e)] = stats.frames.get(int(e), 0) + int(m.sum())
                if lab is None:
                    continue
                if DENSE_COLUMN in columns and lab.dense is not None:
                    dense[m] = dense_per_frame(lab.dense, ts[m])
                    stats.dense_nan[int(e)] = (stats.dense_nan.get(int(e), 0)
                                               + int(np.isnan(dense[m]).sum()))
                if SUBTASK_COLUMN in columns:
                    sub[m] = subtask_per_frame(lab.subtasks, ts[m])
            arrays = {DENSE_COLUMN: pa.array(dense, type=pa.float32()),
                      SUBTASK_COLUMN: pa.array(sub, type=pa.int64())}
            for c in columns:
                t = t.append_column(new_schema.field(c), arrays[c])
            w.write_table(t.replace_schema_metadata(new_schema.metadata),
                          row_group_size=max(1, len(t)))


