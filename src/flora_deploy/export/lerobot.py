# From a job in a store


def _index_dataset(store: Any, job_id: str) -> dict[str, Any]:
    from flora_deploy.jobs.indexing import summary_path

    p = summary_path(job_id)
    if store.exists(p):
        return dict(json.loads(store.get_bytes(p)).get("dataset") or {})
    return {}


def export_job(
    store: Any,
    job_id: str,
    out: str | os.PathLike[str],
    *,
    config_hash: str | None = None,
    source: str | os.PathLike[str] | None = None,
    stages: Sequence[str] | None = None,
    allow_uncertified: bool = False,
    allow_fake: bool = False,
    include_videos: bool = False,
    work_dir: str | os.PathLike[str] | None = None,
    download: Callable[..., str] | None = None,
) -> ExportReport:
    """Export a composed job's labels into a copy of its LeRobot dataset.

    The source is ``source`` when given, else the job's dataset as ``flora index`` recorded it:
    a local directory, or the Hub repo at its pinned revision (``meta/`` and ``data/`` only, plus
    ``videos/`` with ``include_videos``; ``export.hub.fetch_source``)."""
    from flora_deploy.export.results import iter_records, load_summary
    from flora_deploy.jobs.manifest import load_manifest
    from flora_deploy.jobs.store import is_fake_job_id

    summary = load_summary(store, job_id, config_hash=config_hash)
    composed = [s for s in SUPPORTED_STAGES if s in summary.get("stages", {})]
    if stages is None:
        stages = composed
    missing = [s for s in stages if s in SUPPORTED_STAGES and s not in composed]
    if missing:
        raise ExportError(f"job {job_id!r} has no composed {missing} output (composed: "
                          f"{composed or 'none'})")
    records = {s: list(iter_records(store, job_id, s, config_hash=summary["config_hash"]))
               for s in stages if s in SUPPORTED_STAGES}
    try:
        manifest = load_manifest(store, job_id, summary["config_hash"])
        planned = [e.uid for e in manifest.episodes]
        reasons = {u: f"unplanned: {r}" for u, r in manifest.excluded.items()}
    except FileNotFoundError:
        planned, reasons = None, {}
    for item in summary.get("poison_pills", ()):
        reasons.setdefault(str(item).split("/")[0], "poison_pill")
    ds = _index_dataset(store, job_id)
    if source is None:
        if ds.get("repo"):
            from flora_deploy.export.hub import fetch_source

            work = Path(work_dir) if work_dir else Path(out).parent / f".{Path(out).name}.source"
            source = fetch_source(ds["repo"], ds.get("revision") or "", ds.get("subdir") or "",
                                  work, include_videos=include_videos, download=download)
        elif ds.get("name"):
            source = ds["name"]
        else:
            raise ExportError(f"job {job_id!r} has no index summary naming its dataset; pass "
                              "--source <dataset dir>")
    job = {"job_id": job_id, "config_hash": summary["config_hash"],
           "generation": summary.get("generation"), "status": summary.get("status"),
           "stage_hashes": summary.get("stage_hashes", {})}
    src_info = {k: ds.get(k) for k in ("name", "repo", "revision", "subdir", "format")
                if ds.get(k) is not None}
    return export_lerobot(source, out, records, stages=list(stages),
                          allow_uncertified=allow_uncertified, allow_fake=allow_fake,
                          fake_job=is_fake_job_id(job_id), include_videos=include_videos,
                          source_info=src_info, job_info=job, episode_reasons=reasons,
                          planned_uids=planned)
