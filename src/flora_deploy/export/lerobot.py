@dataclass
class ExportReport:
    out: str
    codebase_version: str
    stages: list[str]
    episodes: int
    labeled: int
    unlabeled: list[dict[str, Any]]  # episodes missing a label, with the stages and reasons
    records: dict[str, int]  # certified / uncertified / fake
    allow_uncertified: bool
    allow_fake: bool
    videos_included: bool
    dense_uncovered: list[dict[str, Any]] = field(default_factory=list)
    job: dict[str, Any] = field(default_factory=dict)
    source: dict[str, Any] = field(default_factory=dict)
    pushed: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return {"schema": REPORT_SCHEMA, **asdict(self)}


def _check_out(source: Path, out: Path) -> None:
    s, o = source.resolve(), out.resolve()
    if o == s or s in o.parents or o in s.parents:
        raise ExportError(f"--out {out} overlaps the source dataset {source}; the source is "
                          "never modified, pick a separate directory")
    if out.exists() and (not out.is_dir() or any(out.iterdir())):
        raise ExportError(f"--out {out} exists and is not empty")


def _ignore(source: Path, skip: set[str], include_videos: bool) -> Callable[[str, list[str]],
                                                                            set[str]]:
    """``copytree``'s ``ignore``: drops ``skip`` (files the export rewrites), caches and (unless
    ``include_videos``) ``videos/``, and refuses (ExportError) any symlink that resolves outside
    the source dataset (review 12 F4: a ``meta/notes.md -> ~/.ssh/id_ed25519`` would otherwise be
    copied into the export and pushed). Links into the dataset itself, or into its own HF cache
    ``blobs/`` (``media.safepath``), are copied as the file they name."""
    def ignore(d: str, names: list[str]) -> set[str]:
        rel = Path(d).relative_to(source) if Path(d).is_relative_to(source) else \
            Path(d).resolve().relative_to(source.resolve())
        out = set()
        for n in names:
            r = (rel / n).as_posix()
            if r in skip or n in (".git", ".cache", ".scratch", "__pycache__"):
                out.add(n)
            elif r == "videos" and not include_videos:
                out.add(n)
            elif (Path(d) / n).is_symlink() and not is_within(source, Path(d) / n):
                raise ExportError(f"{source}: {r} is a symlink that resolves outside the "
                                  "dataset; refusing to copy it into the export")
        return out
    return ignore


def export_lerobot(
    source: str | os.PathLike[str],
    out: str | os.PathLike[str],
    records: Mapping[str, Sequence[StageRecord]],
    *,
    stages: Sequence[str] | None = None,
    allow_uncertified: bool = False,
    allow_fake: bool = False,
    fake_job: bool = False,
    include_videos: bool = False,
    source_info: Mapping[str, Any] | None = None,
    job_info: Mapping[str, Any] | None = None,
    episode_reasons: Mapping[str, str] | None = None,
    planned_uids: Iterable[str] | None = None,
) -> ExportReport:
    """Write a labeled copy of the LeRobot dataset at ``source`` to ``out`` (module docstring).

    ``records`` maps stage -> composed records; ``stages`` picks which are exported (default:
    every supported stage present). ``source_info`` (repo, revision, subdir, name) is recorded as
    provenance and in the video note. ``episode_reasons`` (uid -> why it has no record) and
    ``planned_uids`` (the job's planned episodes) explain unlabeled episodes in the report.
    """
    source, out = Path(source), Path(out)
    stages = list(stages) if stages is not None else [s for s in SUPPORTED_STAGES if records.get(s)]
    bad = [s for s in stages if s not in SUPPORTED_STAGES]
    if bad:
        raise ExportError(f"stages {bad} cannot be exported to LeRobot; choose from "
                          f"{', '.join(SUPPORTED_STAGES)}")
    if not stages:
        raise ExportError("nothing to export: no records in any supported stage")
    layout = open_layout(source)
    _check_out(source, out)
    chosen = [r for s in stages for r in records.get(s, ())]
    counts = check_policy(chosen, allow_uncertified=allow_uncertified, allow_fake=allow_fake,
                          fake_job=fake_job)
    labels_by_id = build_labels(records, stages)

    rows = layout.episode_rows()
    by_index = {int(r["episode_index"]): r for r in rows}
    ids = {f"episode_{e:06d}": e for e in by_index}
    unknown = sorted(set(labels_by_id) - set(ids))
    if unknown:
        raise ExportError(f"{len(unknown)} labeled episodes are not in {source} (first: "
                          f"{unknown[:3]}); is --source the dataset the job labeled?")
    labels = {ids[eid]: lab for eid, lab in labels_by_id.items()}

    sub = subtask_stage(stages)
    fields = [f for f, (_t, need) in EPISODE_FIELDS.items()
              if need is None or (need == "subtasks" and sub) or need in stages]
    columns = ([DENSE_COLUMN] if "reward.dense" in stages else []) + \
              ([SUBTASK_COLUMN] if sub else [])
    clash = [c for c in columns if c in layout.info.get("features", {})]
    if clash:
        raise ExportError(f"{source} already declares {clash} (export from the original dataset)")

    data_files = layout.data_files()
    rewritten = {_rel(p, source) for p in [*data_files, *layout.episode_files()]}
    rewritten |= {"meta/info.json", "README.md", REPORT_NAME}

    tmp = out.parent / f".{out.name}.flora-export-tmp-{os.getpid()}"
    if tmp.exists():
        shutil.rmtree(tmp)
    out.parent.mkdir(parents=True, exist_ok=True)
    try:
        shutil.copytree(source, tmp, ignore=_ignore(source, rewritten, include_videos))
        stats = _FrameStats()
        for f in data_files:
            _rewrite_data(f, _dst(tmp, _rel(f, source)), labels, columns, stats)
        layout.write_episodes(tmp, labels, fields)

        # Report: episodes with a missing label, and frames dense alignment left NaN.
        dataset = next((r.dataset for r in chosen), (source_info or {}).get("name", ""))
        reasons = dict(episode_reasons or {})
        planned = set(planned_uids) if planned_uids is not None else None
        rec_ids = {s: {r.episode_id for r in records.get(s, ())} for s in stages}
        unlabeled = []
        for e in sorted(by_index):
            eid = f"episode_{e:06d}"
            missing = [s for s in stages if eid not in rec_ids[s]]
            if not missing:
                continue
            uid = episode_uid(dataset, eid) if dataset else eid
            why = reasons.get(uid) or ("not_in_job" if planned is not None and uid not in planned
                                       else "excluded")
            unlabeled.append({"episode_index": e, "episode_id": eid, "uid": uid,
                              "missing_stages": missing, "reason": why})
        dense_uncovered = [{"episode_index": e, "frames": stats.frames.get(e, 0),
                            "nan_frames": n} for e, n in sorted(stats.dense_nan.items()) if n]

        src = {"path": str(source), **dict(source_info or {}),
               "codebase_version": layout.info.get("codebase_version")}
        info = dict(layout.info)
        feats = dict(info.get("features", {}))
        for c in columns:
            feats[c] = dict(FRAME_FEATURES[c])
        info["features"] = feats
        info["flora"] = {
            "schema": EXPORT_SCHEMA,
            "labels_schema": "flora_labels_v1",
            "framework": f"flora-deploy {flora_deploy.__version__}",
            "job": dict(job_info or {}),
            "stages": stages,
            "subtasks_from": sub,
            "source": src,
            "videos": {"included": include_videos,
                       "note": None if include_videos else video_note(src)},
            "policy": {"allow_uncertified": allow_uncertified, "allow_fake": allow_fake,
                       "records": counts},
            "episode_fields": {f: str(EPISODE_FIELDS[f][0]) for f in fields},
            "frame_features": columns,
            "dense_reward": None if DENSE_COLUMN not in columns else {
                "column": DENSE_COLUMN, "step_s": DENSE_STEP_S, "time_eps_s": TIME_EPS_S,
                "values": {"1": "failure", "2": "suboptimal", "3": "normal"},
                "rule": "frame at timestamp t gets per_step[floor((t + 1e-4) / 0.5)]; NaN when "
                        "that step does not exist or the episode has no dense record"},
            "subtask_index": None if SUBTASK_COLUMN not in columns else {
                "column": SUBTASK_COLUMN,
                "rule": "first flora_subtasks[i] with start_s <= t + 1e-4 < end_s, else -1"},
            "unlabeled_episodes": len(unlabeled),
            "license": LABEL_LICENSE,
        }
        (tmp / "meta" / "info.json").write_text(json.dumps(info, indent=4, allow_nan=False)
                                                + "\n", encoding="utf-8")
        report = ExportReport(
            out=str(out), codebase_version=str(layout.info.get("codebase_version")),
            stages=stages, episodes=len(by_index),
            labeled=len(by_index) - len(unlabeled), unlabeled=unlabeled, records=counts,
            allow_uncertified=allow_uncertified, allow_fake=allow_fake,
            videos_included=include_videos, dense_uncovered=dense_uncovered,
            job=dict(job_info or {}), source=src)
        from flora_deploy.export.hub import dataset_card

        (tmp / "README.md").write_text(dataset_card(info, report), encoding="utf-8")
        (tmp / REPORT_NAME).write_text(json.dumps(report.to_dict(), indent=2, sort_keys=True,
                                                  allow_nan=False) + "\n", encoding="utf-8")
        if out.exists():
            out.rmdir()  # empty (checked above)
        os.replace(tmp, out)
    except BaseException:
        shutil.rmtree(tmp, ignore_errors=True)
        raise
    return report


def video_note(src: Mapping[str, Any]) -> str:
    """How to put the source videos next to an export made without them."""
    repo, rev = src.get("repo"), src.get("revision")
    if repo:
        sub = (src.get("subdir") or "").strip("/")
        inc = f"{sub}/videos/*" if sub else "videos/*"
        return (f"videos are not copied; they are unchanged in the source {repo}@{rev}. Fetch "
                f"them into this directory with: hf download {repo} --repo-type dataset "
                f"--revision {rev} --include '{inc}' --local-dir <dir>"
                + (f" (then move {sub}/videos here)" if sub else ""))
    return (f"videos are not copied; copy {src.get('path')}/videos into this directory (paths "
            "are unchanged)")


