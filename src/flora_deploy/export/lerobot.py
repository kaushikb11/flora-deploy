@dataclass(frozen=True)
class EpisodeLabels:
    """Everything one episode receives. ``None`` fields are written as null."""

    subtasks: tuple[dict[str, Any], ...] | None = None
    terminal_score: int | None = None
    terminal_expected: float | None = None
    dense: tuple[int, ...] | None = None
    provenance: tuple[dict[str, Any], ...] = ()
    certified: bool | None = None


def record_kind(rec: StageRecord) -> str:
    """``fake`` (fake engines, never real labels), ``certified`` or ``uncertified``."""
    from flora_deploy.validate.certify import is_fake

    if rec.uncertified_reason == "fake_models" or is_fake(rec.provenance):
        return "fake"
    return "certified" if rec.certified else "uncertified"


def check_policy(records: Iterable[StageRecord], *, allow_uncertified: bool, allow_fake: bool,
                 fake_job: bool = False) -> dict[str, int]:
    """Count records by :func:`record_kind`; raise :class:`ExportRefused` when the policy does
    not allow some of them. The whole export is refused: records are never silently dropped."""
    counts = {"certified": 0, "uncertified": 0, "fake": 0}
    reasons: dict[str, int] = {}
    for r in records:
        k = record_kind(r)
        counts[k] += 1
        if k == "uncertified":
            reasons[str(r.uncertified_reason)] = reasons.get(str(r.uncertified_reason), 0) + 1
    problems = []
    if (counts["fake"] or fake_job) and not allow_fake:
        problems.append(f"{counts['fake']} records were made by fake models (a fake-models run "
                        "is never a real label); pass --allow-fake to export them anyway")
    if counts["uncertified"] and not allow_uncertified:
        why = ", ".join(f"{k}: {v}" for k, v in sorted(reasons.items()))
        problems.append(f"{counts['uncertified']} records are uncertified ({why}); pass "
                        "--allow-uncertified to export them anyway")
    if problems:
        raise ExportRefused("refusing to export: " + "; ".join(problems))
    return counts


def _prov(rec: StageRecord) -> dict[str, Any]:
    p = rec.provenance
    return {"stage": rec.stage, "preset": p.preset, "engine": p.engine,
            "certified": rec.certified, "uncertified_reason": rec.uncertified_reason,
            "certificate": p.certificate, "config_hash": p.config_hash,
            "framework": p.framework}


def subtask_stage(stages: Sequence[str]) -> str | None:
    """The stage subtasks come from: ``caption`` (it carries the segments) over ``segment``."""
    return "caption" if "caption" in stages else "segment" if "segment" in stages else None


def build_labels(records: Mapping[str, Sequence[StageRecord]], stages: Sequence[str]
                 ) -> dict[str, EpisodeLabels]:
    """Episode id -> labels from the records of ``stages``. One dataset per export."""
    sub = subtask_stage(stages)
    by_ep: dict[str, dict[str, StageRecord]] = {}
    datasets = set()
    for stage in stages:
        for r in records.get(stage, ()):
            datasets.add(r.dataset)
            if stage in by_ep.get(r.episode_id, {}):
                raise ExportError(f"{r.uid}: two {stage} records")
            by_ep.setdefault(r.episode_id, {})[stage] = r
    if len(datasets) > 1:
        raise ExportError(f"records come from several datasets {sorted(datasets)}; a LeRobot "
                          "export takes one")
    out: dict[str, EpisodeLabels] = {}
    for eid, recs in by_ep.items():
        kw: dict[str, Any] = {}
        if sub is not None and sub in recs:
            segs = sorted(recs[sub].segments, key=lambda s: (s.start_s, s.end_s, s.event_id))
            kw["subtasks"] = tuple({"start_s": float(s.start_s), "end_s": float(s.end_s),
                                    "caption": s.caption} for s in segs)
        t = recs.get("reward.terminal")
        if t is not None and t.terminal is not None:
            kw["terminal_score"] = int(t.terminal.score)
            kw["terminal_expected"] = float(t.terminal.expected_score)
        d = recs.get("reward.dense")
        if d is not None and d.dense is not None:
            kw["dense"] = tuple(int(v) for v in d.dense.per_step)
        used = [recs[s] for s in stages if s in recs and (s != "segment" or sub == "segment")]
        kw["provenance"] = tuple(_prov(r) for r in used)
        kw["certified"] = all(r.certified for r in used) if used else None
        out[eid] = EpisodeLabels(**kw)
    return out


# ---------------------------------------------------------------------------------------------
# Alignment (pure; docs/export.md "Dense alignment")


def dense_step_index(timestamps: Sequence[float] | np.ndarray,
                     step_s: float = DENSE_STEP_S) -> np.ndarray:
    """The 0.5 s step each frame time falls in: ``floor((t + 1e-4) / step_s)``."""
    t = np.asarray(timestamps, dtype=np.float64)
    return np.floor((t + TIME_EPS_S) / step_s).astype(np.int64)


def dense_per_frame(per_step: Sequence[int] | None, timestamps: Sequence[float] | np.ndarray,
                    step_s: float = DENSE_STEP_S) -> np.ndarray:
    """float32 per frame: ``per_step[k]`` for the frame's step ``k``; NaN when no step covers
    the frame (``k`` out of range, negative time, or no dense record)."""
    t = np.asarray(timestamps, dtype=np.float64)
    out = np.full(t.shape, np.nan, dtype=np.float32)
    if not per_step or not len(t):
        return out
    k = dense_step_index(t, step_s)
    steps = np.asarray(per_step, dtype=np.float32)
    ok = (t >= 0) & (k >= 0) & (k < len(steps))
    out[ok] = steps[k[ok]]
    return out


def subtask_per_frame(subtasks: Sequence[Mapping[str, Any]] | None,
                      timestamps: Sequence[float] | np.ndarray) -> np.ndarray:
    """int64 per frame: index of the first subtask with ``start_s <= t + 1e-4 < end_s``, else
    -1. ``subtasks`` are in ``flora_subtasks`` order (by ``start_s``)."""
    t = np.asarray(timestamps, dtype=np.float64) + TIME_EPS_S
    out = np.full(t.shape, -1, dtype=np.int64)
    for i, s in enumerate(subtasks or ()):
        hit = (out == -1) & (t >= float(s["start_s"])) & (t < float(s["end_s"]))
        out[hit] = i
    return out


