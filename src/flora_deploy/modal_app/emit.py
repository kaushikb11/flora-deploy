"""``flora deploy --emit out.py``: the app ``build_app(cfg)`` builds, as a standalone script.

The script is for review (and for ``modal deploy out.py`` if you prefer Modal's CLI): it imports
the same undecorated module-scope workers and functions and applies the same decorators with every
option written out literally, from the same :class:`~flora_deploy.modal_app.factory.AppPlan`.
Secrets appear by *name* only (``modal.Secret.from_name``); env values are the plan's
non-secret settings. ``PLAN`` at the end is the plan itself, so a reviewer (or a test) can check
the decorators against it.
"""

from __future__ import annotations

import json
import re

from flora_deploy.modal_app.factory import IMAGE_BUILDERS, AppPlan, ObjectSpec, VolumeMount


def _var(name: str) -> str:
    return "vol_" + re.sub(r"\W", "_", name)


def _volumes(o: ObjectSpec) -> str:
    items = [f"{path!r}: {_var(m.name)}" + (".read_only()" if m.read_only else "")
             for path, m in o.volumes.items()]
    return "{" + ", ".join(items) + "}"


def _kwargs(o: ObjectSpec) -> list[str]:
    """Keyword arguments in ``factory.modal_kwargs`` order, rendered as source."""
    kw = [f"image=images.{IMAGE_BUILDERS[o.image]}()",
          f"cpu={o.cpu!r}",
          f"memory={o.memory!r}",
          f"timeout={o.timeout!r}",
          f"volumes={_volumes(o)}",
          "secrets=[" + ", ".join(f"modal.Secret.from_name({s!r})" for s in o.secrets) + "]",
          f"env={dict(o.env)!r}"]
    for key in ("gpu", "startup_timeout", "min_containers", "max_containers",
                "scaledown_window", "region"):
        value = getattr(o, key)
        if value is not None:
            kw.append(f"{key}={value!r}")
    if o.retries:
        r = o.retries
        kw.append(f"retries=modal.Retries(max_retries={int(r['max_retries'])!r}, "
                  f"initial_delay={r['initial_delay']!r}, "
                  f"backoff_coefficient={r['backoff_coefficient']!r})")
    if o.nonpreemptible:
        kw.append("nonpreemptible=True")
    if o.schedule:
        kw.append(f"schedule=modal.Cron({o.schedule!r})")
    return kw


def render_script(plan: AppPlan) -> str:
    """Python source equivalent to ``factory.materialize(plan)``, deploying as ``app``."""
    imports: dict[tuple[str, str], str] = {}
    used: set[str] = set()
    for o in plan.objects:
        key = (o.module, o.attr)
        if key not in imports:
            alias = o.attr if o.attr not in used else f"{o.attr}_{len(used)}"
            used.add(alias)
            imports[key] = alias
    volumes: dict[str, VolumeMount] = {}
    for o in plan.objects:
        for m in o.volumes.values():
            volumes.setdefault(m.name, m)

    # No config value is interpolated into source text: the docstring is fixed, and each value
    # is a repr() literal on the right of an assignment (review 11b F2). The schema restricts
    # modal.environment / region / tags too; this is the second line of defence.
    out = [
        '"""Modal app generated by `flora deploy --emit` (APP_NAME, PROJECT, PRESET,',
        "MODAL_ENVIRONMENT and CONFIG_HASH below).",
        "",
        "Equivalent to flora_deploy.modal_app.factory.build_app(cfg) for this config. Deploy with",
        "`modal deploy -e <MODAL_ENVIRONMENT> <this file>` or `flora deploy --config ...`.",
        "No secret values are written here: secrets are referenced by name.",
        '"""',
        "",
        "import json",
        "",
        "import modal",
        "",
        "from flora_deploy.modal_app import images",
    ]
    for (module, attr), alias in imports.items():
        out.append(f"from {module} import {attr}" + (f" as {alias}" if alias != attr else ""))
    out += ["", f"APP_NAME = {plan.app_name!r}",
            f"PROJECT = {plan.project!r}",
            f"PRESET = {plan.preset!r}",
            f"MODAL_ENVIRONMENT = {plan.environment!r}",
            f"CONFIG_HASH = {plan.config_hash!r}",
            f"app = modal.App(APP_NAME, tags={dict(plan.tags)!r})", ""]
    for name, m in volumes.items():
        out.append(f"{_var(name)} = modal.Volume.from_name({name!r}, version=2, "
                   f"create_if_missing={m.create!r})")
    for o in plan.objects:
        label = f"{o.kind} {o.name}" + (f" (shard kinds: {', '.join(o.shard_kinds)})"
                                         if o.shard_kinds else "")
        out += ["", "# " + json.dumps(label)[1:-1]]  # one line: control characters escaped
        target = imports[(o.module, o.attr)]
        if o.kind == "cls":
            out.append("app.cls(")
            if o.max_inputs:
                target = f"modal.concurrent(max_inputs={o.max_inputs!r})({target})"
        else:
            out.append("app.function(")
            out.append(f"    name={o.name!r},")
        out += [f"    {k}," for k in _kwargs(o)]
        out.append(f")({target})")
    plan_json = json.dumps(plan.to_json(), sort_keys=True)
    out += ["", "# The plan these decorators were rendered from (flora_deploy AppPlan).",
            f"PLAN = json.loads({plan_json!r})", ""]
    return "\n".join(out)


def write_script(plan: AppPlan, path) -> str:
    from pathlib import Path

    src = render_script(plan)
    compile(src, str(path), "exec")  # never write a script that does not parse
    Path(path).write_text(src, encoding="utf-8")
    return src
